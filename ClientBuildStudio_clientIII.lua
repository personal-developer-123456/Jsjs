local function rotateSelection(axisName, degrees)
	if #selection == 0 then return end
	local pivot = primaryPart().Position
	local R = CFrame.fromAxisAngle(AXES[axisName], math.rad(degrees))
	changeParts("Rotate", selection, function()
		for _, p in ipairs(selection) do p.CFrame = CFrame.new(pivot) * R * CFrame.new(-pivot) * p.CFrame end
	end)
end

local function nudgeSelection(direction)
	if #selection == 0 then return end
	local step = gridStep()
	changeParts("Move", selection, function()
		for _, p in ipairs(selection) do p.CFrame = p.CFrame + direction * step end
	end)
end

local function snapSelectionToGrid()
	if #selection == 0 then return end
	local step = gridStep()
	changeParts("Snap to grid", selection, function()
		for _, p in ipairs(selection) do p.CFrame = CFrame.new(snapVector(p.Position, step) - p.Position) * p.CFrame end
	end)
end

local function rotatePlacement(axisName)
	local R = CFrame.fromAxisAngle(AXES[axisName], math.rad(angleStep()))
	state.rotation = R * state.rotation
	ui.notify("Rotated " .. axisName .. " " .. angleStep() .. "deg")
end

-- One rotate command for the buttons / hotkeys: acts on selection or placement
local function rotateAction(axisName)
	if state.tool == "Select" and #selection > 0 then
		rotateSelection(axisName, angleStep())
	else
		rotatePlacement(axisName)
	end
end

local function clearAll()
	local parts = {}
	for _, p in ipairs(container:GetChildren()) do table.insert(parts, p) end
	deleteParts(parts)
	ui.notify("Cleared " .. #parts .. " parts")
