-- Replaces Roblox's built-in Handles / ArcHandles with a custom gizmo:
--   Move   = 6 arrows + 3 plane squares + centre ball (free drag on screen plane)
--   Rotate = a ball with 3 coloured rings (grab a ring and drag around it)
--   Scale  = a handle on every face of the primary part (Alt = scale from centre)
-- Why it feels better: constant on-screen size, always drawn on top, big grab
-- areas (bigger again on touch), hover highlight, and the drag follows the
-- pointer exactly (ray maths against the axis / ring, no "distance" guessing).
-- Ctrl while dragging flips snapping, Esc cancels the drag.
-- NOTE: the script is right at Lua's 200-local limit, so everything lives in
-- this do-block. The only thing shared with the rest of the file is ui.gizmo.
do
	local ContextActionService = game:GetService("ContextActionService")
	local GuiService = game:GetService("GuiService")

	local COLORS = { Color3.fromRGB(235, 70, 70), Color3.fromRGB(95, 205, 95), Color3.fromRGB(70, 130, 245) }
	local AXIS_NAMES = { "X", "Y", "Z" }
	local HOVER_COLOR = Color3.fromRGB(255, 232, 110)
	local BALL_COLOR = Color3.fromRGB(205, 210, 225)
	local SIZE_FRACTION = 0.13 -- gizmo radius = this * distance to the camera
	local GRAB = CONFIG.IsTouch and 1.7 or 1 -- grab-area multiplier
	local RING_SEGMENTS = 40 -- drawn segments per ring
	local RING_SAMPLES = 72 -- hit-test samples per ring
	local LOCAL_AXES = { Vector3.xAxis, Vector3.yAxis, Vector3.zAxis }
	local FACE_DIRS = { Vector3.xAxis, -Vector3.xAxis, Vector3.yAxis, -Vector3.yAxis, Vector3.zAxis, -Vector3.zAxis }
	-- rotation that points a part's local Z axis along world X / Y / Z
	local AXIS_ROT = { CFrame.Angles(0, math.rad(90), 0), CFrame.Angles(math.rad(-90), 0, 0), CFrame.new() }

	local G = {
		Origin = Vector3.zero, Basis = CFrame.new(), CF = CFrame.new(), Axes = LOCAL_AXES,
		S = 1, Mode = "Move", ShownMode = nil, GuideOn = false,
		Hover = nil, Drag = nil, LastUsed = 0, Dirty = true,
		Bounds = Vector3.zero, BoundsAt = 0, LastS = 0, ColorKey = nil,
	}
	ui.gizmo = G

	local function sizeComp(sz, axis)
		return axis == 1 and sz.X or (axis == 2 and sz.Y or sz.Z)
	end

	local function signed(v)
		return (v >= 0 and "+" or "") .. fmt(round(v, 3))
	end

	--// ray maths ------------------------------------------------------------
	local function rayPointDist(o, d, p)
		local w = p - o
		local t = w:Dot(d)
		if t <= 0 then return math.huge end
		return (w - d * t).Magnitude
	end

	-- closest distance between the ray and the segment a->b
	local function raySegment(o, d, a, b)
		local ab = b - a
		local w0 = a - o
		local aa, bb, dd, ee = ab:Dot(ab), ab:Dot(d), ab:Dot(w0), d:Dot(w0)
		local denom = aa - bb * bb
		local sp = 0
		if denom > 1e-6 then sp = (bb * ee - dd) / denom end
		sp = math.clamp(sp, 0, 1)
		local t = ee + sp * bb
		if t <= 0 then return math.huge end
		return ((a + ab * sp) - (o + d * t)).Magnitude
	end

	-- distance along the line p0 + s*u that is closest to the ray (nil if edge-on)
	local function axisParam(o, d, p0, u)
		local w0 = p0 - o
		local bb = u:Dot(d)
		local denom = 1 - bb * bb
		if denom < 0.01 then return nil end
		return (bb * d:Dot(w0) - u:Dot(w0)) / denom
	end

	local function rayPlane(o, d, p0, n)
		local dn = d:Dot(n)
		if math.abs(dn) < 1e-4 then return nil end
		local t = (p0 - o):Dot(n) / dn
		if t <= 0 then return nil end
		return o + d * t
	end

	-- ray under the mouse, or under a touch input object (also returns viewport pixels)
	local function pointerRay(input)
		local cam = Workspace.CurrentCamera
		if input and input.UserInputType == Enum.UserInputType.Touch then
			local pos = input.Position
			return cam:ScreenPointToRay(pos.X, pos.Y), Vector2.new(pos.X, pos.Y) + GuiService:GetGuiInset()
		end
		local loc = UserInputService:GetMouseLocation()
		return cam:ViewportPointToRay(loc.X, loc.Y), loc
	end

	--// snapping ---------------------------------------------------------------
	local function snapOn()
		local on = state.snapEnabled
		if UserInputService:IsKeyDown(Enum.KeyCode.LeftControl) or UserInputService:IsKeyDown(Enum.KeyCode.RightControl) then
			on = not on
		end
		return on
	end

	local function snapLen(v)
		return snapOn() and snap(v, gridStep()) or v
	end

	--// visuals ----------------------------------------------------------------
	-- one invisible anchor part; every adornment is an offset from it. The anchor
	-- sits on the gizmo origin with the gizmo basis, so item CFrames are in gizmo space.
	local anchor = create("Part", {
		Name = "GizmoAnchor", Anchored = true, CanCollide = false, CanQuery = false, CanTouch = false,
		CastShadow = false, Transparency = 1, Size = Vector3.new(0.1, 0.1, 0.1), Locked = true,
	})
	local items = { Move = {}, Rotate = {}, Scale = {} }

	local function newItem(mode, id, className, color, zIndex, alpha)
		local a = Instance.new(className)
		a.Adornee = anchor
		a.AlwaysOnTop = true
		a.ZIndex = zIndex
		a.Color3 = color
		a.Transparency = alpha
		a.Visible = false
		a.Parent = adornFolder
		local it = { Id = id, Adorn = a, Color = color, Alpha = alpha, Update = function() end }
		table.insert(items[mode], it)
		return it
	end

	-- MOVE: arrows (both directions), plane squares, centre ball, drag guide line
	local TIP_RADII = { 0.095, 0.07, 0.047, 0.024 }
	for i = 1, 3 do
		local dir, rot, col = LOCAL_AXES[i], AXIS_ROT[i], COLORS[i]
		for sg = -1, 1, 2 do
			local shaft = newItem("Move", "M" .. i, "CylinderHandleAdornment", col, 4, 0)
			shaft.Update = function(s)
				shaft.Adorn.Radius = 0.022 * s
				shaft.Adorn.Height = 0.8 * s
				shaft.Adorn.CFrame = CFrame.new(dir * (0.6 * sg * s)) * rot
			end
			for k = 1, #TIP_RADII do
				local tip = newItem("Move", "M" .. i, "CylinderHandleAdornment", col, 4, 0)
				tip.Update = function(s)
					tip.Adorn.Radius = TIP_RADII[k] * s
					tip.Adorn.Height = 0.065 * s
					tip.Adorn.CFrame = CFrame.new(dir * ((0.97 + 0.06 * k) * sg * s)) * rot
				end
			end
		end
		local j, k2 = (i % 3) + 1, ((i + 1) % 3) + 1
		local plane = newItem("Move", "P" .. i, "BoxHandleAdornment", col, 3, 0.35)
		local planeRot = CFrame.fromMatrix(Vector3.zero, LOCAL_AXES[j], LOCAL_AXES[k2])
		plane.Update = function(s)
			plane.Adorn.Size = Vector3.new(0.3 * s, 0.3 * s, 0.01 * s)
			plane.Adorn.CFrame = CFrame.new((LOCAL_AXES[j] + LOCAL_AXES[k2]) * (0.35 * s)) * planeRot
		end
	end
	local centre = newItem("Move", "C", "SphereHandleAdornment", Color3.fromRGB(235, 235, 235), 5, 0.1)
	centre.Update = function(s)
		centre.Adorn.Radius = 0.12 * s
	end
	local guide = newItem("Move", "G", "BoxHandleAdornment", COLORS[1], 2, 0.4)
	guide.Update = function(s)
		guide.Adorn.Size = Vector3.new(0.012 * s, 0.012 * s, 800)
	end

	-- ROTATE: translucent ball + 3 rings
	local ball = newItem("Rotate", "B", "SphereHandleAdornment", BALL_COLOR, 1, 0.88)
	ball.Update = function(s)
		ball.Adorn.Radius = 0.985 * s
	end
	local segLen = 2 * math.sin(math.pi / RING_SEGMENTS) * 1.25
	for i = 1, 3 do
		local j, k = (i % 3) + 1, ((i + 1) % 3) + 1
		for n = 1, RING_SEGMENTS do
			local th = ((n - 0.5) / RING_SEGMENTS) * math.pi * 2
			local radial = LOCAL_AXES[j] * math.cos(th) + LOCAL_AXES[k] * math.sin(th)
			local rot = CFrame.fromMatrix(Vector3.zero, radial, LOCAL_AXES[i])
			local seg = newItem("Rotate", "R" .. i, "BoxHandleAdornment", COLORS[i], 3, 0)
			seg.Update = function(s)
				seg.Adorn.Size = Vector3.new(0.034 * s, 0.034 * s, segLen * s)
				seg.Adorn.CFrame = CFrame.new(radial * s) * rot
			end
		end
	end

	-- SCALE: one handle per face of the primary part
	for f = 1, 6 do
		local axis = math.ceil(f / 2)
		local it = newItem("Scale", "S" .. f, "BoxHandleAdornment", COLORS[axis], 4, 0)
		it.Update = function(s)
			local p = primaryPart()
			if not p then return end
			local half = sizeComp(p.Size, axis) / 2
			it.Adorn.Size = Vector3.new(0.13 * s, 0.13 * s, 0.13 * s)
			it.Adorn.CFrame = CFrame.new(FACE_DIRS[f] * (half + 0.12 * s))
		end
	end

	-- floating "+3" / "45deg" label that follows the pointer while dragging
	local readout = create("TextLabel", {
		Name = "GizmoReadout", AnchorPoint = Vector2.new(0, 1), AutomaticSize = Enum.AutomaticSize.X,
		Size = UDim2.fromOffset(0, 26), BackgroundColor3 = THEME.Panel, BackgroundTransparency = 0.1,
		Text = "", Font = THEME.FontBold, TextSize = 14, TextColor3 = THEME.Text, Visible = false,
		ZIndex = 60, Parent = gui,
	}, {
		create("UICorner", { CornerRadius = UDim.new(0, 8) }),
		create("UIPadding", { PaddingLeft = UDim.new(0, 10), PaddingRight = UDim.new(0, 10) }),
	})

	local function setVisibility(mode, guideOn)
		for m, list in pairs(items) do
			local on = m == mode
			for _, it in ipairs(list) do
				it.Adorn.Visible = on and (it.Id ~= "G" or guideOn)
			end
		end
		G.ShownMode, G.GuideOn = mode, guideOn
		G.Dirty = true
	end

	local function refreshColors(mode)
		local D = G.Drag
		local active = D and D.Id or G.Hover
		for _, it in ipairs(items[mode] or {}) do
			if it.Id ~= "B" and it.Id ~= "G" then
				local a = it.Adorn
				if active == it.Id then
					a.Color3 = HOVER_COLOR
					a.Transparency = math.min(it.Alpha, 0.1)
				else
					a.Color3 = it.Color
					a.Transparency = D and math.clamp(it.Alpha + 0.6, 0, 0.92) or it.Alpha
				end
			end
		end
	end

	--// hit testing ------------------------------------------------------------
	-- returns id ("M1".."M3" arrows, "P1".."P3" planes, "C" centre, "R1".."R3" rings,
	-- "S1".."S6" scale faces) and, for rings, the world point that was grabbed
	local function hitTest(ray)
		local o, d = ray.Origin, ray.Direction.Unit
		local O, ax, s, mode = G.Origin, G.Axes, G.S, G.Mode
		local bestId, bestScore, bestMeta
		local function consider(id, score, meta)
			if score < 1 and (not bestId or score < bestScore) then
				bestId, bestScore, bestMeta = id, score, meta
			end
		end

		if mode == "Move" then
			local tol = 0.12 * s * GRAB
			for i = 1, 3 do
				for sg = -1, 1, 2 do
					local dist = raySegment(o, d, O + ax[i] * (0.18 * sg * s), O + ax[i] * (1.3 * sg * s))
					consider("M" .. i, dist / tol, nil)
				end
				local j, k = (i % 3) + 1, ((i + 1) % 3) + 1
				local p = rayPlane(o, d, O, ax[i])
				if p then
					local rel = p - O
					local u, v = rel:Dot(ax[j]) / s, rel:Dot(ax[k]) / s
					local lo, hi = 0.17 - 0.03 * GRAB, 0.53 + 0.03 * GRAB
					if u >= lo and u <= hi and v >= lo and v <= hi then consider("P" .. i, 0.45, nil) end
				end
			end
			consider("C", rayPointDist(o, d, O) / (0.16 * s * GRAB), nil)
		elseif mode == "Rotate" then
			local tol = 0.1 * s * GRAB
			for i = 1, 3 do
				local j, k = (i % 3) + 1, ((i + 1) % 3) + 1
				local bestD, bestP = math.huge, nil
				for n = 0, RING_SAMPLES - 1 do
					local th = (n / RING_SAMPLES) * math.pi * 2
					local p = O + (ax[j] * math.cos(th) + ax[k] * math.sin(th)) * s
					local dist = rayPointDist(o, d, p)
					if dist < bestD then bestD, bestP = dist, p end
				end
				if bestP then consider("R" .. i, bestD / tol, bestP) end
			end
		elseif mode == "Scale" then
			local p = primaryPart()
			if p then
				local tol = 0.16 * s * GRAB
				for f = 1, 6 do
					local half = sizeComp(p.Size, math.ceil(f / 2)) / 2
					local pos = G.CF:PointToWorldSpace(FACE_DIRS[f] * (half + 0.12 * s))
					consider("S" .. f, rayPointDist(o, d, pos) / tol, nil)
				end
			end
		end
		return bestId, bestMeta
	end

	--// dragging ---------------------------------------------------------------
	local function beginDrag(id, meta, ray, input, screenPos)
		local p = primaryPart()
		if not p then return false end
		local cam = Workspace.CurrentCamera
		local o, dv = ray.Origin, ray.Direction.Unit
		local kind, idx = id:sub(1, 1), tonumber(id:sub(2))
		local D = {
			Id = id, Kind = kind, Index = idx,
			Input = (input and input.UserInputType == Enum.UserInputType.Touch) and input or nil,
			Origin = G.Origin, Basis = G.Basis, Axes = { G.Axes[1], G.Axes[2], G.Axes[3] },
			Offset = Vector3.zero, Value = 0,
			Before = snapshotMany(selection), StartCFs = {},
			Primary = p, PrimaryCF = p.CFrame, PrimarySize = p.Size,
		}
		for _, part in ipairs(selection) do D.StartCFs[part] = part.CFrame end

		if kind == "M" then
			D.Dir = D.Axes[idx]
			D.T0 = axisParam(o, dv, D.Origin, D.Dir)
			if not D.T0 then return false end
			guide.Adorn.CFrame = AXIS_ROT[idx]
			guide.Adorn.Color3 = COLORS[idx]
		elseif kind == "P" then
			D.Normal = D.Axes[idx]
			D.A, D.B = D.Axes[(idx % 3) + 1], D.Axes[((idx + 1) % 3) + 1]
			D.P0 = rayPlane(o, dv, D.Origin, D.Normal)
			if not D.P0 then return false end
		elseif kind == "C" then
			D.Normal = cam.CFrame.LookVector
			D.P0 = rayPlane(o, dv, D.Origin, D.Normal)
			if not D.P0 then return false end
		elseif kind == "R" then
			D.Normal = D.Axes[idx]
			local rel = meta - D.Origin
			rel = rel - D.Normal * rel:Dot(D.Normal)
			if rel.Magnitude < 1e-4 then return false end
			D.U = rel.Unit
			D.V = D.Normal:Cross(D.U)
			D.Total = 0
			-- face-on rings: follow the cursor around the ring (plane maths).
			-- edge-on rings: fall back to dragging along the ring's on-screen tangent.
			local p0 = math.abs(dv:Dot(D.Normal)) >= 0.25 and rayPlane(o, dv, D.Origin, D.Normal) or nil
			if p0 then
				D.PlaneMode = true
				local r0 = p0 - D.Origin
				D.Last = math.atan2(r0:Dot(D.V), r0:Dot(D.U))
			else
				D.PlaneMode = false
				D.Pointer0 = screenPos
				local s0 = cam:WorldToViewportPoint(meta)
				local s1 = cam:WorldToViewportPoint(meta + D.V * (0.25 * G.S))
				local sv = Vector2.new(s1.X - s0.X, s1.Y - s0.Y)
				D.ScreenDir = sv.Magnitude > 0.5 and sv.Unit or nil
				local dist = math.max((G.Origin - cam.CFrame.Position).Magnitude, 1)
				D.PxPerRad = math.max(G.S / (2 * dist * math.tan(math.rad(cam.FieldOfView) / 2)) * cam.ViewportSize.Y, 20)
			end
		elseif kind == "S" then
			local axis = math.ceil(idx / 2)
			D.AxisIndex = axis
			D.Dir = D.PrimaryCF:VectorToWorldSpace(FACE_DIRS[idx])
			D.Face0 = D.PrimaryCF.Position + D.Dir * (sizeComp(D.PrimarySize, axis) / 2)
			D.T0 = axisParam(o, dv, D.Face0, D.Dir)
			if not D.T0 then return false end
		else
			return false
		end

		G.Drag = D
		G.LastUsed = os.clock()
		G.LastS = 0
		return true
	end

	local function applyOffset(D)
		for part, cf in pairs(D.StartCFs) do part.CFrame = cf + D.Offset end
	end

	local function updateDrag(ray, screenPos)
		local D = G.Drag
		local o, dv = ray.Origin, ray.Direction.Unit
		local kind = D.Kind
		local text

		if kind == "M" then
			local t = axisParam(o, dv, D.Origin, D.Dir)
			if t then
				D.Value = snapLen(t - D.T0)
				D.Offset = D.Dir * D.Value
				applyOffset(D)
			end
			text = AXIS_NAMES[D.Index] .. " " .. signed(D.Value)
		elseif kind == "P" then
			local p = rayPlane(o, dv, D.Origin, D.Normal)
			if p then
				local rel = p - D.P0
				D.ValueA, D.ValueB = snapLen(rel:Dot(D.A)), snapLen(rel:Dot(D.B))
				D.Offset = D.A * D.ValueA + D.B * D.ValueB
				applyOffset(D)
			end
			text = signed(D.ValueA or 0) .. ", " .. signed(D.ValueB or 0)
		elseif kind == "C" then
			local p = rayPlane(o, dv, D.Origin, D.Normal)
			if p then
				local rel = p - D.P0
				D.Offset = Vector3.new(snapLen(rel.X), snapLen(rel.Y), snapLen(rel.Z))
				applyOffset(D)
			end
			text = string.format("X %s  Y %s  Z %s", signed(D.Offset.X), signed(D.Offset.Y), signed(D.Offset.Z))
		elseif kind == "R" then
			if D.PlaneMode then
				if math.abs(dv:Dot(D.Normal)) > 0.1 then
					local p = rayPlane(o, dv, D.Origin, D.Normal)
					if p then
						local rel = p - D.Origin
						local a = math.atan2(rel:Dot(D.V), rel:Dot(D.U))
						local da = (a - D.Last + math.pi) % (math.pi * 2) - math.pi
						D.Total = D.Total + da -- accumulates, so you can spin past 360
						D.Last = a
					end
				end
			elseif D.ScreenDir then
				D.Total = (screenPos - D.Pointer0):Dot(D.ScreenDir) / D.PxPerRad
			end
			local deg = math.deg(D.Total)
			if snapOn() then deg = snap(deg, angleStep()) end
			D.Value = deg
			local R = CFrame.fromAxisAngle(D.Normal, math.rad(deg))
			local pivot = D.Origin
			for part, cf in pairs(D.StartCFs) do
				part.CFrame = CFrame.new(pivot) * R * CFrame.new(-pivot) * cf
			end
			text = AXIS_NAMES[D.Index] .. " " .. fmt(round(deg, 1)) .. "°"
		elseif kind == "S" then
			local t = axisParam(o, dv, D.Face0, D.Dir)
			if t then
				local delta = snapLen(t - D.T0)
				local sym = UserInputService:IsKeyDown(Enum.KeyCode.LeftAlt) or UserInputService:IsKeyDown(Enum.KeyCode.RightAlt)
				local startAxis = sizeComp(D.PrimarySize, D.AxisIndex)
				local newAxis = math.clamp(startAxis + delta * (sym and 2 or 1), CONFIG.MinSize, CONFIG.MaxSize)
				local grow = newAxis - startAxis
				local sz = D.PrimarySize
				if D.Primary:IsA("Part") and D.Primary.Shape == Enum.PartType.Ball then
					sz = Vector3.new(newAxis, newAxis, newAxis)
				elseif D.AxisIndex == 1 then
					sz = Vector3.new(newAxis, sz.Y, sz.Z)
				elseif D.AxisIndex == 2 then
					sz = Vector3.new(sz.X, newAxis, sz.Z)
				else
					sz = Vector3.new(sz.X, sz.Y, newAxis)
				end
				D.Primary.Size = sz
				D.Primary.CFrame = D.PrimaryCF + D.Dir * (sym and 0 or grow / 2)
				D.Value = newAxis
				D.Sym = sym
			end
			text = "Size " .. fmt(round(D.Value, 2)) .. (D.Sym and " (centred)" or "")
		end

		readout.Text = text or ""
		readout.Position = UDim2.fromOffset(screenPos.X + 22, screenPos.Y - 18)
		readout.Visible = true
	end

	local DRAG_NAMES = { M = "Move", P = "Move", C = "Move", R = "Rotate", S = "Scale" }

	local function endDrag()
		local D = G.Drag
		if not D then return end
		G.Drag = nil
		G.LastUsed = os.clock()
		G.Dirty = true
		readout.Visible = false
		commitChange(DRAG_NAMES[D.Kind], D.Before)
		ui.refreshContext()
	end

	local function cancelDrag()
		local D = G.Drag
		if not D then return end
		G.Drag = nil
		G.LastUsed = os.clock()
		G.Dirty = true
		readout.Visible = false
		for part, s in pairs(D.Before) do restore(part, s) end
		ui.notify("Cancelled")
	end

	--// per-frame update -------------------------------------------------------
	local function selectionCenter()
		local lo, hi
		for _, part in ipairs(selection) do
			local cf, sz = part.CFrame, part.Size
			local pos = cf.Position
			local h = Vector3.new(
				halfExtentAlong(cf, sz, Vector3.xAxis),
				halfExtentAlong(cf, sz, Vector3.yAxis),
				halfExtentAlong(cf, sz, Vector3.zAxis)
			)
			local a, b = pos - h, pos + h
			if lo then
				lo, hi = lo:Min(a), hi:Max(b)
			else
				lo, hi = a, b
			end
		end
		return (lo + hi) / 2
	end

	local function hide()
		if G.ShownMode then setVisibility(nil, false) end
		G.Hover = nil
		readout.Visible = false
	end

	local function step()
		local cam = Workspace.CurrentCamera
		local p = primaryPart()
		if not cam or not p or state.tool ~= "Select" then
			G.Drag = nil
			hide()
			return
		end
		if anchor.Parent ~= cam then anchor.Parent = cam end

		local D = G.Drag
		if D then
			local ray, loc = pointerRay(D.Input)
			updateDrag(ray, loc)
		end

		local mode = state.handleMode
		if D then mode = D.Kind == "R" and "Rotate" or (D.Kind == "S" and "Scale" or "Move") end

		local origin, basis
		if mode == "Scale" then
			origin, basis = p.Position, p.CFrame.Rotation
		elseif D then
			origin, basis = D.Origin + D.Offset, D.Basis
		else
			local now = os.clock()
			if #selection <= 120 or now - G.BoundsAt > 0.15 then
				G.Bounds = selectionCenter()
				G.BoundsAt = now
			end
			origin = G.Bounds
			basis = state.handleSpace == "Local" and p.CFrame.Rotation or CFrame.new()
		end

		local camCF = cam.CFrame
		if camCF:PointToObjectSpace(origin).Z >= 0 then -- behind the camera
			hide()
			return
		end

		local s = math.max((origin - camCF.Position).Magnitude, 2) * SIZE_FRACTION
		local cf = CFrame.new(origin) * basis
		G.Origin, G.Basis, G.S, G.Mode, G.CF = origin, basis, s, mode, cf
		G.Axes = { cf.XVector, cf.YVector, cf.ZVector }
		anchor.CFrame = cf

		-- hover highlight (mouse only)
		if not D then
			local mouseLike = UserInputService.MouseEnabled and UserInputService:GetLastInputType() ~= Enum.UserInputType.Touch
			if mouseLike then
				local ray, loc = pointerRay(nil)
				G.Hover = (not isOverUI(loc)) and hitTest(ray) or nil
			else
				G.Hover = nil
			end
		end

		local guideOn = D ~= nil and D.Kind == "M"
		if G.ShownMode ~= mode or G.GuideOn ~= guideOn then setVisibility(mode, guideOn) end

		local key = (D and ("d" .. D.Id) or ("h" .. tostring(G.Hover))) .. mode
		local recolor = key ~= G.ColorKey
		local relayout = G.Dirty or mode == "Scale" or math.abs(s - G.LastS) > s * 0.004
		if relayout then
			for _, it in ipairs(items[mode]) do it.Update(s) end
			G.LastS = s
			G.Dirty = false
			recolor = true
		end
		if recolor then
			refreshColors(mode)
			G.ColorKey = key
		end
	end

	-- pressing on a handle: sink the input so the camera / world click never sees it
	local function onInput(_, inputState, input)
		if inputState ~= Enum.UserInputState.Begin then return Enum.ContextActionResult.Pass end
		if G.Drag or not G.ShownMode then return Enum.ContextActionResult.Pass end
		local ray, loc = pointerRay(input)
		if isOverUI(loc) then return Enum.ContextActionResult.Pass end
		local id, meta = hitTest(ray)
		if id and beginDrag(id, meta, ray, input, loc) then
			G.Hover = nil
			return Enum.ContextActionResult.Sink
		end
		return Enum.ContextActionResult.Pass
	end

	ContextActionService:BindActionAtPriority(
		"BuildStudioGizmo", onInput, false, Enum.ContextActionPriority.High.Value,
		Enum.UserInputType.MouseButton1, Enum.UserInputType.Touch
	)

	connect(RunService.RenderStepped, step)
	connect(UserInputService.InputEnded, function(input)
		local D = G.Drag
		if not D then return end
		if (D.Input and input == D.Input) or (not D.Input and input.UserInputType == Enum.UserInputType.MouseButton1) then
			endDrag()
		end
	end)
	connect(UserInputService.InputBegan, function(input)
		if G.Drag and input.KeyCode == Enum.KeyCode.Escape then cancelDrag() end
	end)
	connect(UserInputService.WindowFocusReleased, endDrag)

	gui.Destroying:Connect(function()
		ContextActionService:UnbindAction("BuildStudioGizmo")
		anchor:Destroy()
	end)

	-- the rest of the script calls this whenever selection / tool / mode changes
	refreshHandles = function()
		G.Dirty = true
	end
end

