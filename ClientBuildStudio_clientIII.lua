end

local function multiSelectActive()
	return state.multiSelect
		or UserInputService:IsKeyDown(Enum.KeyCode.LeftShift)
		or UserInputService:IsKeyDown(Enum.KeyCode.RightShift)
end

-- Called for a mouse click or a touch tap that hit the 3D world
local function onWorldPointer(ray)
	local result = castRay(ray)
	local part = result and getBuildPart(result.Instance)
	local tool = state.tool

	if tool == "Build" then
		if not result then return end
		state.aim = result
		if not state.confirmPlace then placeAtAim() end
	elseif tool == "Select" then
		if part then
			if multiSelectActive() then
				toggleSelect(part)
			else
				selectOnly(part)
			end
		elseif not multiSelectActive() then
			-- ignore the click if it was really a gizmo press / drag that just ended
			local g = ui.gizmo
			if not g.Drag and os.clock() - g.LastUsed > 0.3 then
				clearSelection()
				selectionChanged()
			end
		end
	elseif tool == "Paint" and part then
		applyStyleToParts({ part }, paintStyle())
	elseif tool == "Delete" and part then
		deleteParts({ part })
	elseif tool == "Pick" and part then
		eyedrop(part)
	end
end

connect(UserInputService.InputBegan, function(input, processed)
	if processed or UserInputService:GetFocusedTextBox() then return end
	if input.UserInputType == Enum.UserInputType.MouseButton1 then
		local loc = UserInputService:GetMouseLocation()
		if not isOverUI(loc) then onWorldPointer(Workspace.CurrentCamera:ViewportPointToRay(loc.X, loc.Y)) end
	elseif input.UserInputType == Enum.UserInputType.Keyboard then
		local key = input.KeyCode
		local ctrl = UserInputService:IsKeyDown(Enum.KeyCode.LeftControl)
			or UserInputService:IsKeyDown(Enum.KeyCode.RightControl)
			or UserInputService:IsKeyDown(Enum.KeyCode.LeftMeta)
		if ctrl and key == Enum.KeyCode.Z then
			undo()
		elseif ctrl and key == Enum.KeyCode.Y then
			redo()
		elseif ctrl and key == Enum.KeyCode.D then
			duplicateSelection()
		elseif ctrl and (key == Enum.KeyCode.Two or key == Enum.KeyCode.Three or key == Enum.KeyCode.Four) then
			state.handleMode = key == Enum.KeyCode.Two and "Move" or (key == Enum.KeyCode.Three and "Scale" or "Rotate")
			if state.tool ~= "Select" then setTool("Select") end
			refreshHandles()
			refreshAll()
		elseif key == Enum.KeyCode.Delete or key == Enum.KeyCode.Backspace then
			deleteParts(table.clone(selection))
		elseif key == Enum.KeyCode.R then
			rotateAction("Y")
		elseif key == Enum.KeyCode.F then
			rotateAction("X")
		elseif key == Enum.KeyCode.T then
			rotateAction("Z")
		elseif key == Enum.KeyCode.Return and state.tool == "Build" then
			placeAtAim()
		elseif key.Value >= Enum.KeyCode.One.Value and key.Value <= Enum.KeyCode.Five.Value then
			setTool(TOOLS[key.Value - Enum.KeyCode.One.Value + 1])
		end
	end
end)

connect(UserInputService.TouchTapInWorld, function(position, processedByUI)
	if processedByUI then return end
	onWorldPointer(Workspace.CurrentCamera:ScreenPointToRay(position.X, position.Y))
end)

connect(RunService.RenderStepped, function()
	if state.tool == "Build" and hoverAimActive() then updateHoverAim() end
	updateGhost()
end)

