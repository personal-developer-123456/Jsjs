	for _, p in ipairs(eligibleParts()) do
		local screen, onScreen = cam:WorldToViewportPoint(p.Position)
		if onScreen and screen.X >= topLeft.X and screen.X <= bottomRight.X and screen.Y >= topLeft.Y and screen.Y <= bottomRight.Y then
			addToSelection(p)
			hits = hits + 1
		end
	end
	selectionChanged()
	if hits > 0 then ui.notify("Box-selected " .. hits) end
end

connect(UserInputService.InputBegan, function(input, processed)
	if processed or UserInputService:GetFocusedTextBox() then return end
	if input.UserInputType ~= Enum.UserInputType.MouseButton1 then return end
	if state.tool ~= "Select" then return end
	local altDown = UserInputService:IsKeyDown(Enum.KeyCode.LeftAlt) or UserInputService:IsKeyDown(Enum.KeyCode.RightAlt)
	if not altDown then return end
	local loc = UserInputService:GetMouseLocation()
	if isOverUI(loc) then return end
	marquee = { StartPos = Vector2.new(loc.X, loc.Y), Additive = multiSelectActive() }
	updateMarqueeFrame(marquee.StartPos, marquee.StartPos)
	marqueeFrame.Visible = true
end)
connect(UserInputService.InputChanged, function(input)
	if marquee and input.UserInputType == Enum.UserInputType.MouseMovement then
		local loc = UserInputService:GetMouseLocation()
		updateMarqueeFrame(marquee.StartPos, Vector2.new(loc.X, loc.Y))
	end
end)
connect(UserInputService.InputEnded, function(input)
	if marquee and input.UserInputType == Enum.UserInputType.MouseButton1 then
		local loc = UserInputService:GetMouseLocation()
		finishMarquee(Vector2.new(loc.X, loc.Y))
	end
end)

