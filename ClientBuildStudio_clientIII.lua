--// SAVE / LOAD (JSON) -------------------------------------------------------
local function serialize()
	local list = {}
	for _, p in ipairs(container:GetChildren()) do
		if p:IsA("BasePart") then
			local rx, ry, rz = p.CFrame:ToOrientation()
			table.insert(list, {
				s = p:GetAttribute("BuildShape") or "Block",
				p = { round(p.Position.X, 3), round(p.Position.Y, 3), round(p.Position.Z, 3) },
				o = { round(rx, 4), round(ry, 4), round(rz, 4) },
				z = { round(p.Size.X, 3), round(p.Size.Y, 3), round(p.Size.Z, 3) },
				c = p.Color:ToHex(),
				m = p.Material.Name,
				t = round(p.Transparency, 2),
				r = round(p.Reflectance, 2),
				a = p.Anchored,
				k = p.CanCollide,
			})
		end
	end
	return HttpService:JSONEncode({ v = 1, parts = list })
end

local function importBuild(text)
	local ok, data = pcall(function()
		return HttpService:JSONDecode(text)
	end)
	if not ok or type(data) ~= "table" or type(data.parts) ~= "table" then
		ui.notify("Import failed: invalid data")
		return
	end
	local created = {}
	for _, e in ipairs(data.parts) do
		if partCount() >= CONFIG.MaxParts then break end
		local okPart, part = pcall(function()
			local cf = CFrame.new(e.p[1], e.p[2], e.p[3]) * CFrame.fromOrientation(e.o[1], e.o[2], e.o[3])
			return createPart(e.s, Vector3.new(e.z[1], e.z[2], e.z[3]), cf, {
				Color = Color3.fromHex(e.c),
				Material = materialFromName(e.m),
				Transparency = e.t or 0,
				Reflectance = e.r or 0,
				Anchored = e.a ~= false,
				CanCollide = e.k ~= false,
			})
		end)
		if okPart and part then table.insert(created, part) end
	end
	if #created == 0 then
		ui.notify("Nothing imported")
		return
	end
	pushAction("Import " .. #created, function()
		forget(created)
		for _, p in ipairs(created) do p.Parent = nil end
	end, function()
		for _, p in ipairs(created) do p.Parent = container end
	end)
	ui.notify("Imported " .. #created .. " parts")
end

--// RAYCASTING / PLACEMENT / GHOST -------------------------------------------
local ghost
local rayParams = RaycastParams.new()
rayParams.FilterType = Enum.RaycastFilterType.Exclude

local function castRay(ray)
	local ignore = { ghost }
	if player.Character then table.insert(ignore, player.Character) end
	rayParams.FilterDescendantsInstances = ignore
	return Workspace:Raycast(ray.Origin, ray.Direction * CONFIG.MaxPlaceDistance, rayParams)
end

local function isOverUI(pos)
	for _, frame in ipairs(uiRegions) do
		if frame.Visible then
			local ap, as = frame.AbsolutePosition, frame.AbsoluteSize
			if pos.X >= ap.X and pos.X <= ap.X + as.X and pos.Y >= ap.Y and pos.Y <= ap.Y + as.Y then return true end
		end
	end
	return false
end

-- Offset the hit point so the part rests on the surface, then snap to grid
local function computePlacementCF(result)
	if not result then return nil end
	local size = placementSize()
	local normal = result.Normal
	local half = halfExtentAlong(state.rotation, size, normal)
	local pos = result.Position + normal * half
	if state.snapEnabled then
		local step = gridStep()
		local function axis(v, n)
			if math.abs(n) > 0.9 then
				return v -- keep the surface-contact axis exact
			end
			return snap(v, step)
		end
		pos = Vector3.new(axis(pos.X, normal.X), axis(pos.Y, normal.Y), axis(pos.Z, normal.Z))
	end
	return CFrame.new(pos) * state.rotation
end

local function rebuildGhost()
	if ghost then ghost:Destroy() end
	local def = state.shape
	ghost = Instance.new(def.Class)
	if def.Shape then ghost.Shape = def.Shape end
	ghost.Name = "BuildGhost"
	ghost.Anchored = true
	ghost.CanCollide = false
	ghost.CanQuery = false
	ghost.CanTouch = false
	ghost.CastShadow = false
	ghost.Material = Enum.Material.SmoothPlastic
	ghost.Color = THEME.Accent
	ghost.Transparency = 0.55
end

local function updateGhost()
	local cf = state.tool == "Build" and state.showGhost and computePlacementCF(state.aim) or nil
	if not cf then
		ghost.Parent = nil
		return
	end
	ghost.Size = placementSize()
	ghost.CFrame = cf
	ghost.Parent = Workspace.CurrentCamera
end

-- True when the ghost should follow the mouse cursor (desktop hover)
local function hoverAimActive()
	if state.confirmPlace or not UserInputService.MouseEnabled then return false end
	return UserInputService:GetLastInputType() ~= Enum.UserInputType.Touch
end

local function updateHoverAim()
	local loc = UserInputService:GetMouseLocation()
	if isOverUI(loc) then
		state.aim = nil
		return
	end
	state.aim = castRay(Workspace.CurrentCamera:ViewportPointToRay(loc.X, loc.Y))
end

local function placeAtAim()
	local cf = computePlacementCF(state.aim)
	if not cf then
		ui.notify("Tap a surface first")
		return
	end
	placePart(cf)
	state.aim = nil
end

