--// CAMERA: FOCUS SELECTION + PRESETS -------------------------------------------
local function selectionBoundsCenter()
	if #selection == 0 then return nil, 0 end
	local minV, maxV
	for _, p in ipairs(selection) do
		local half = p.Size / 2
		local signs = { -1, 1 }
		for _, sx in ipairs(signs) do
			for _, sy in ipairs(signs) do
				for _, sz in ipairs(signs) do
					local corner_ = p.CFrame * Vector3.new(half.X * sx, half.Y * sy, half.Z * sz)
					minV = minV and Vector3.new(math.min(minV.X, corner_.X), math.min(minV.Y, corner_.Y), math.min(minV.Z, corner_.Z)) or corner_
					maxV = maxV and Vector3.new(math.max(maxV.X, corner_.X), math.max(maxV.Y, corner_.Y), math.max(maxV.Z, corner_.Z)) or corner_
				end
			end
		end
	end
	return (minV + maxV) / 2, (maxV - minV).Magnitude / 2
end

local cameraTween
local cameraToken = 0
local function flyCameraTo(cf, duration)
	local cam = Workspace.CurrentCamera
	if not cam then return end
	if cameraTween then cameraTween:Cancel() end
	cameraToken = cameraToken + 1
	local token = cameraToken
	cam.CameraType = Enum.CameraType.Scriptable
	cameraTween = TweenService:Create(cam, TweenInfo.new(duration or 0.5, Enum.EasingStyle.Quad, Enum.EasingDirection.Out), { CFrame = cf })
	cameraTween:Play()
	cameraTween.Completed:Connect(function()
		if token == cameraToken then cam.CameraType = Enum.CameraType.Custom end
	end)
end

local function focusPoint()
	local center, radius = selectionBoundsCenter()
	if center then return center, radius end
	local hrp = player.Character and player.Character:FindFirstChild("HumanoidRootPart")
	if hrp then return hrp.Position, 12 end
	local cam = Workspace.CurrentCamera
	return cam and cam.CFrame.Position or Vector3.new(), 20
end

local function focusSelection()
	local center, radius = focusPoint()
	local cam = Workspace.CurrentCamera
	local dist = math.max(radius * 2.4, 10)
	local dir = Vector3.new(1, 0.6, 1).Unit
	if cam then
		local offset = cam.CFrame.Position - center
		if offset.Magnitude > 0.1 then dir = offset.Unit end
	end
	flyCameraTo(CFrame.new(center + dir * dist, center))
	ui.notify(#selection > 0 and "Focused selection" or "Focused on you")
end

local function cameraPreset(kind)
	local center = focusPoint()
	local dist = 40
	local cf
	if kind == "Top-down" then
		cf = CFrame.new(center + Vector3.new(0.001, dist, 0.001), center)
	else -- Isometric
		cf = CFrame.new(center + Vector3.new(dist, dist * 0.8, dist), center)
	end
	flyCameraTo(cf, 0.6)
	ui.notify(kind .. " view")
end

