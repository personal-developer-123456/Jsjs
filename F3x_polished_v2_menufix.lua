-- weak keys: a deleted part keeps its lock / hidden state so undo restores it faithfully,
-- and the entry is garbage-collected together with the part
local lockedParts = setmetatable({}, { __mode = "k" }) -- [part] = true
local hiddenParts = setmetatable({}, { __mode = "k" }) -- [part] = true

local function syncPartFlags(part)
	local locked = lockedParts[part]
	local hidden = hiddenParts[part]
	part.CanQuery = not (locked or hidden) -- keeps raycasts (click/paint/delete) off it
	part.LocalTransparencyModifier = hidden and 1 or 0 -- visual only, doesn't touch real Transparency
end

local function setLocked(part, value)
	lockedParts[part] = value or nil
	syncPartFlags(part)
	if value and selectedSet[part] then
		removeFromSelection(part)
		selectionChanged()
	end
end

local function setHidden(part, value)
	hiddenParts[part] = value or nil
	syncPartFlags(part)
	if value and selectedSet[part] then
		removeFromSelection(part)
		selectionChanged()
	end
end

--// DRAGGABLE / MINIMISABLE MAIN PANEL -----------------------------------------
local function makeDraggable(frame, handle)
	handle = handle or frame
	local dragging, dragStart, startPos, moved

	-- keep part of the title bar on screen so the panel can never be lost
	local function place(x, y, scaleX, scaleY)
		local scale = state.uiScale > 0 and state.uiScale or 1
		local cam = Workspace.CurrentCamera
		if cam and scaleX == 0 and scaleY == 0 then
			local view = cam.ViewportSize / scale
			local minX = 60 - frame.Size.X.Offset
			x = math.clamp(x, minX, math.max(view.X - 60, minX))
			y = math.clamp(y, 0, math.max(view.Y - 40, 0))
		end
		frame.Position = UDim2.new(scaleX, x, scaleY, y)
	end

	local function step(input)
		if not moved then
			-- grace: a tap on the title bar (or a wobbly finger) must not nudge the panel
			if (input.Position - dragStart).Magnitude < (CONFIG.IsTouch and 8 or 3) then return end
			moved = true
			dragStart = input.Position
		end
		local scale = state.uiScale > 0 and state.uiScale or 1
		local delta = (input.Position - dragStart) / scale
		place(startPos.X.Offset + delta.X, startPos.Y.Offset + delta.Y, startPos.X.Scale, startPos.Y.Scale)
	end

	connect(handle.InputBegan, function(input)
		if input.UserInputType == Enum.UserInputType.MouseButton1 or input.UserInputType == Enum.UserInputType.Touch then
			dragging = true
			moved = false
			dragStart = input.Position
			startPos = frame.Position
			local conn
			conn = input.Changed:Connect(function()
				if input.UserInputState == Enum.UserInputState.End then
					dragging = false
					conn:Disconnect()
				end
			end)
		end
	end)
	connect(UserInputService.InputChanged, function(input)
		if dragging and (input.UserInputType == Enum.UserInputType.MouseMovement or input.UserInputType == Enum.UserInputType.Touch) then
			if input.UserInputType == Enum.UserInputType.MouseMovement
				and not UserInputService:IsMouseButtonPressed(Enum.UserInputType.MouseButton1) then
				dragging = false -- release was missed (cursor left the window)
				return
			end
			step(input)
		end
	end)

	-- rotating the phone / resizing the window used to be able to strand the panel off screen
	local function reclamp()
		local p = frame.Position
		place(p.X.Offset, p.Y.Offset, p.X.Scale, p.Y.Scale)
	end
	local cam = Workspace.CurrentCamera
	if cam then connect(cam:GetPropertyChangedSignal("ViewportSize"), reclamp) end
end

