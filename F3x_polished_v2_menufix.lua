local function slider(parent, title, minV, maxV, step, getValue, setValue, onCommit)
	local holder = create("Frame", { BackgroundTransparency = 1, Size = UDim2.new(1, 0, 0, 48), Parent = parent })
	label(holder, title, { Size = UDim2.new(0.6, 0, 0, 18), Color = THEME.SubText, TextSize = 12 })
	local valueLabel = label(holder, "", {
		Size = UDim2.new(0.4, 0, 0, 18), Position = UDim2.fromScale(0.6, 0), Align = Enum.TextXAlignment.Right, TextSize = 12,
	})
	local track = create("Frame", {
		Position = UDim2.new(0, 0, 0, 30), Size = UDim2.new(1, 0, 0, 8), BackgroundColor3 = THEME.Item, Parent = holder,
	})
	corner(track, 4)
	local fill = create("Frame", { Size = UDim2.fromScale(0, 1), BackgroundColor3 = THEME.Accent, Parent = track })
	corner(fill, 4)
	local knob = create("Frame", {
		AnchorPoint = Vector2.new(0.5, 0.5), Position = UDim2.fromScale(0, 0.5), Size = UDim2.fromOffset(22, 22),
		BackgroundColor3 = Color3.new(1, 1, 1), Parent = track,
	})
	corner(knob, 11)
	local hit = create("TextButton", {
		Text = "", BackgroundTransparency = 1, Position = UDim2.new(0, -8, 0, 16), Size = UDim2.new(1, 16, 0, 32), Parent = holder,
	})
	local scroller = parent:IsA("ScrollingFrame") and parent or parent:FindFirstAncestorWhichIsA("ScrollingFrame")
	local drag -- the finger / mouse button currently on this slider

	local function fractionOf(v)
		return math.clamp((v - minV) / (maxV - minV), 0, 1)
	end

	local function render()
		local v = getValue()
		local a = fractionOf(v)
		fill.Size = UDim2.fromScale(a, 1)
		knob.Position = UDim2.fromScale(a, 0.5)
		valueLabel.Text = fmt(v)
	end

	local function commit(a)
		setValue(math.clamp(snap(minV + (maxV - minV) * a, step), minV, maxV))
		refreshAll()
	end

	local function atX(x)
		return math.clamp((x - track.AbsolutePosition.X) / math.max(track.AbsoluteSize.X, 1), 0, 1)
	end

	-- always ends a drag: gives scrolling back and fires onCommit if the value was changed
	local function finish()
		local d = drag
		if not d then return end
		drag = nil
		knob.Size = UDim2.fromOffset(22, 22)
		if scroller then scroller.ScrollingEnabled = true end
		if d.engaged and onCommit then onCommit() end
	end
	table.insert(fx.menu.cancels, finish)

	local function engage(d)
		d.engaged = true
		knob.Size = UDim2.fromOffset(28, 28) -- bigger knob = clearly "grabbed"
		if scroller then scroller.ScrollingEnabled = false end -- stop the page scrolling while sliding
	end

	hit.InputBegan:Connect(function(input)
		if drag then return end -- ignore a second finger
		local t = input.UserInputType
		if t == Enum.UserInputType.MouseButton1 then
			-- mouse: no scroll conflict, so take over at once (click jumps the knob there)
			drag = { input = input, mouse = true }
			engage(drag)
			commit(atX(input.Position.X))
		elseif t == Enum.UserInputType.Touch then
			-- touch: GRACE. Nothing changes yet; the finger has to show what it wants first.
			--   sideways swipe  -> slide the knob (relative, so it never jumps under the finger)
			--   vertical swipe  -> the user is scrolling the menu, leave the slider alone
			--   quick still tap -> jump to that spot (on release)
			drag = {
				input = input, x = input.Position.X, y = input.Position.Y, a = fractionOf(getValue()),
				t = os.clock(), canvasY = scroller and scroller.CanvasPosition.Y or 0,
				rejected = fx.menu.busy(hit), -- landed on a moving page: it only wants to stop it
			}
		end
	end)

	connect(UserInputService.InputChanged, function(input)
		local d = drag
		if not d then return end
		if d.mouse then
			if input.UserInputType ~= Enum.UserInputType.MouseMovement then return end
			if not UserInputService:IsMouseButtonPressed(Enum.UserInputType.MouseButton1) then
				finish() -- the release happened outside the window: don't stay stuck to the cursor
				return
			end
			commit(atX(input.Position.X))
			return
		end
		local state0 = d.input.UserInputState
		if state0 == Enum.UserInputState.End or state0 == Enum.UserInputState.Cancel then
			finish() -- missed end event: never leave scrolling disabled
			return
		end
		if input ~= d.input or d.rejected then return end
		local dx, dy = input.Position.X - d.x, input.Position.Y - d.y
		if not d.engaged then
			local grace = CONFIG.SliderGrace
			if math.abs(dy) > grace and math.abs(dy) >= math.abs(dx) then
				d.rejected = true -- scrolling: hands off until the finger lifts
				return
			end
			if math.abs(dx) < grace or math.abs(dx) <= math.abs(dy) then return end
			engage(d)
			d.x, d.a = input.Position.X, fractionOf(getValue()) -- start sliding from where the knob is now
			return
		end
		commit(math.clamp(d.a + dx / math.max(track.AbsoluteSize.X, 1), 0, 1))
	end)

	connect(UserInputService.InputEnded, function(input)
		local d = drag
		if not d then return end
		if d.mouse then
			if input.UserInputType == Enum.UserInputType.MouseButton1 then finish() end
			return
		end
		if input ~= d.input then return end
		if CONFIG.SliderTapToSet and not d.engaged and not d.rejected and os.clock() - d.t < 0.35
			and not (scroller and math.abs(scroller.CanvasPosition.Y - d.canvasY) > 2) then
			engage(d)
			commit(atX(input.Position.X)) -- a deliberate quick tap: jump to the touched spot
		end
		finish()
	end)

	holder.Destroying:Connect(finish)
	refresher(render)
	return holder
end

local function stepper(parent, title, step, minV, maxV, getValue, setValue)
