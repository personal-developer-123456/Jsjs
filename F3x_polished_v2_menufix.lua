	end

	local function addLights()
		if #selection == 0 then
			ui.notify("Select a part first")
			return
		end
		local entries = {}
		for _, part in ipairs(selection) do
			local old = part:FindFirstChildWhichIsA("Light")
			if old then old.Parent = nil end
			local new = fx.makeLight(part, ls.kind, {
				color = ls.partColor and part.Color or state.color,
				brightness = ls.brightness, range = ls.range, shadows = ls.shadows,
			})
			table.insert(entries, { part = part, old = old, new = new })
		end
		pushAction("Add lights " .. #entries, function()
			for _, e in ipairs(entries) do
				e.new.Parent = nil
				if e.old then e.old.Parent = e.part end
			end
		end, function()
			for _, e in ipairs(entries) do
				if e.old then e.old.Parent = nil end
				e.new.Parent = e.part
			end
		end)
		ui.notify("Added " .. #entries .. " light(s)")
	end

	local function removeLights()
		local entries = {}
		for _, part in ipairs(selection) do
			local old = part:FindFirstChildWhichIsA("Light")
			if old then
				old.Parent = nil
				table.insert(entries, { part = part, old = old })
			end
		end
		if #entries == 0 then
			ui.notify("No lights on the selection")
			return
		end
		pushAction("Remove lights " .. #entries, function()
			for _, e in ipairs(entries) do e.old.Parent = e.part end
		end, function()
			for _, e in ipairs(entries) do e.old.Parent = nil end
		end)
		ui.notify("Removed " .. #entries .. " light(s)")
	end

