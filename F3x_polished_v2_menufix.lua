			ExposureCompensation = 0.3, FogEnd = 100000, FogColor = rgb(10, 12, 25) },
			{ bloom = 0.7, rays = 0, haze = 0.15, sat = -0.05, contrast = 0.1, tint = rgb(200, 215, 255) } },
