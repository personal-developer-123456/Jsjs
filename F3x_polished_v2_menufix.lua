local function eligibleParts()
	local list = {}
	for _, p in ipairs(container:GetChildren()) do
		if p:IsA("BasePart") and not lockedParts[p] and not hiddenParts[p] then
			table.insert(list, p)
		end
	end
	return list
end

local function selectMatching(predicate, label_)
	local ref = primaryPart()
	if not ref then
		ui.notify("Select a part first")
		return
	end
	clearSelection()
	local hits = 0
	for _, p in ipairs(eligibleParts()) do
		if predicate(p, ref) then
			addToSelection(p)
			hits = hits + 1
		end
	end
	selectionChanged()
	ui.notify(label_ .. ": " .. hits)
end

local function selectInRadius()
	local ref = primaryPart()
	if not ref then
		ui.notify("Select a part first")
		return
	end
	local r = state.selectRadius
	clearSelection()
	local hits = 0
	for _, p in ipairs(eligibleParts()) do
		if (p.Position - ref.Position).Magnitude <= r then
			addToSelection(p)
			hits = hits + 1
		end
	end
	selectionChanged()
