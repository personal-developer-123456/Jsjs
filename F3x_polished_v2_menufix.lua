			ExposureCompensation = 0.2, FogEnd = 100000, FogColor = rgb(30, 0, 60) },
			{ bloom = 1.4, rays = 0, haze = 0.3, sat = 0.5, contrast = 0.2, tint = rgb(255, 210, 255) } },
		{ "Foggy", { ClockTime = 9, Brightness = 2, Ambient = rgb(120, 125, 130), OutdoorAmbient = rgb(140, 145, 150),
			ExposureCompensation = 0, FogEnd = 100000, FogColor = rgb(185, 190, 195) },
			{ bloom = 0.1, rays = 0, haze = 0.9, sat = -0.15, contrast = 0, tint = rgb(235, 240, 245) } },
