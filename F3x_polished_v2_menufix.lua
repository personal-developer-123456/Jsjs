	-- numbers / colours glide to their new value, booleans switch straight away
	local function applyProps(props, seconds)
		local gliding = {}
		for key, value in pairs(props) do
			if typeof(value) == "boolean" then
				Lighting[key] = value
			else
				gliding[key] = value
			end
		end
		tween(Lighting, gliding, seconds)
	end

	local function applyPreset(entry)
		capture()
		applyProps(entry[2], 0.8)
		local effects = entry[3]
		for _, key in ipairs(FX_KEYS) do setFx(key, effects[key] or 0) end
		local grade = effect("color")
		grade.Enabled = true
		grade.TintColor = effects.tint or Color3.new(1, 1, 1)
		grade.Contrast = effects.contrast or 0
		ui.notify("Lighting: " .. entry[1])
		refreshAll()
	end

	local function restoreLighting(instant)
		if saved then
			if instant then
				for key, value in pairs(saved) do pcall(function() Lighting[key] = value end) end
			else
				applyProps(saved, 0.6)
			end
		end
		for key, e in pairs(made) do
			e:Destroy()
			made[key] = nil
		end
		for _, a in ipairs(stashed) do a.Parent = Lighting end
		table.clear(stashed)
		for _, key in ipairs(FX_KEYS) do lv[key] = 0 end
		lv.cycle = false
		saved = nil
	end

	connect(RunService.Heartbeat, function(dt)
		if lv.cycle then Lighting.ClockTime = (Lighting.ClockTime + dt * 0.25) % 24 end
	end)
	gui.Destroying:Connect(function() restoreLighting(true) end)

	--// BUILD EFFECTS: particles, pop-in, sounds --------------------------------
	local function burst(position, color, count)
		local holder = Instance.new("Part")
		holder.Anchored = true
		holder.CanCollide = false
		holder.CanQuery = false
		holder.CanTouch = false
		holder.Transparency = 1
		holder.Size = Vector3.new(0.2, 0.2, 0.2)
		holder.Position = position
		local e = Instance.new("ParticleEmitter")
		e.Rate = 0
		e.Lifetime = NumberRange.new(0.35, 0.7)
		e.Speed = NumberRange.new(5, 11)
		e.SpreadAngle = Vector2.new(180, 180)
		e.Drag = 4
		e.LightEmission = 0.5
		e.Color = ColorSequence.new(color)
		e.Size = NumberSequence.new({ NumberSequenceKeypoint.new(0, 0.5), NumberSequenceKeypoint.new(1, 0) })
		e.Transparency = NumberSequence.new({ NumberSequenceKeypoint.new(0, 0), NumberSequenceKeypoint.new(1, 1) })
		e.Parent = holder
		holder.Parent = Workspace
		e:Emit(count)
		Debris:AddItem(holder, 1.5)
	end

	local function playSound(id, pitch)
		if id == "" then return end
		local s = Instance.new("Sound")
		s.SoundId = id
		s.Volume = 0.45
		s.PlaybackSpeed = pitch * (0.92 + math.random() * 0.16)
		s.Parent = SoundService
		s:Play()
		Debris:AddItem(s, 3)
	end

	fx.placed = function(part)
		if state.fxParticles then
			burst(part.Position, part.Color, math.clamp(math.floor(part.Size.Magnitude * 2), 6, 22))
		end
		if state.fxPop then
			local target = part.Size
			part.Size = target * 0.78
			tween(part, { Size = target }, 0.18, Enum.EasingStyle.Back)
		end
		if state.fxSound then playSound(CONFIG.PlaceSound, 1) end
	end

	fx.removed = function(list)
		if state.fxParticles then
			for i = 1, math.min(#list, 10) do burst(list[i].Position, list[i].Color, 10) end
		end
		if state.fxSound and #list > 0 then playSound(CONFIG.DeleteSound, 0.85) end
	end

	--// HOVER PREVIEW ------------------------------------------------------------
	local hover = create("Highlight", {
		Name = "Hover", FillTransparency = 0.82, OutlineTransparency = 0.15,
		DepthMode = Enum.HighlightDepthMode.Occluded, Parent = fx.markFolder,
	})
	local HOVER_TOOLS = { Select = true, Paint = true, Delete = true, Pick = true }
	local hoverAt = 0

	connect(RunService.RenderStepped, function()
		local now = os.clock()
		if now - hoverAt < 0.03 then return end
		hoverAt = now
		local target
		if state.hlHover and HOVER_TOOLS[state.tool] and mouseLike() and not marquee then
			local g = ui.gizmo
			local loc = UserInputService:GetMouseLocation()
			if not g.Drag and not g.Hover and not isOverUI(loc) then
				local ray = Workspace.CurrentCamera:ViewportPointToRay(loc.X, loc.Y)
				local result = castRay(ray)
				target = fx.pick(ray, result, result and getBuildPart(result.Instance))
				if target and state.tool == "Select" and selectedSet[target] then target = nil end
			end
		end
		hover.Adornee = target
		if target then
			local color = THEME.Accent
			if state.tool == "Delete" then
				color = THEME.Bad
			elseif state.tool == "Paint" then
				color = state.color
			elseif state.tool == "Pick" then
				color = THEME.Text
			end
			hover.FillColor, hover.OutlineColor = color, color
		end
	end)

	--// FORGIVING PICK -------------------------------------------------------------
	-- A thin sphere is swept along the pointer ray, so you no longer have to hit a part
	-- pixel-perfectly (the tolerance is bigger on touch). Not used by the Delete tool.
	local pickParams = RaycastParams.new()
	pickParams.FilterType = Enum.RaycastFilterType.Include

	fx.pick = function(ray, result, direct)
		if direct then return direct end
		local cam = Workspace.CurrentCamera
		if not cam or state.tool == "Delete" then return nil end
		local origin, dir = ray.Origin, ray.Direction.Unit
		local limit = result and (result.Position - origin).Magnitude + 0.5 or CONFIG.MaxPlaceDistance
		local px = CONFIG.IsTouch and 26 or 10 -- tolerance in screen pixels
		local worldPerPixel = 2 * math.tan(math.rad(cam.FieldOfView) / 2) / math.max(cam.ViewportSize.Y, 1)
		local radius = math.clamp(math.min(limit, 150) * worldPerPixel * px, 0.15, 5)
		pickParams.FilterDescendantsInstances = { container }
		local ok, hit = pcall(function()
			return Workspace:Spherecast(origin, radius, dir * limit, pickParams)
		end)
		return ok and hit and getBuildPart(hit.Instance) or nil
	end

	-- everything touching `seed`, found by growing outwards (padded box = face contact counts)
	fx.selectConnected = function(seed, additive)
		fx.overlap.FilterDescendantsInstances = { container }
		local seen, queue = { [seed] = true }, { seed }
		local head = 1
		while head <= #queue and #queue < CONFIG.MaxConnected do
			local cur = queue[head]
			head += 1
			local found = Workspace:GetPartBoundsInBox(cur.CFrame, cur.Size + Vector3.new(0.1, 0.1, 0.1), fx.overlap)
			for _, p in ipairs(found) do
				if not seen[p] and getBuildPart(p) then
					seen[p] = true
					table.insert(queue, p)
				end
			end
		end
		if not additive then clearSelection() end
		for _, p in ipairs(queue) do addToSelection(p) end
		selectionChanged()
		ui.notify("Connected: " .. #queue .. (#queue >= CONFIG.MaxConnected and " (limit)" or ""))
	end

	--// DRAG TO PLACE ----------------------------------------------------------------
	-- Hold the mouse in the Build tool and drag: a part is dropped every time the pointer
	-- has travelled one part-length. The whole stroke is ONE undo step.
	local stroke_ -- { parts = {}, last = Vector3 } while a stroke is running

	local function finishStroke()
		local s = stroke_
		stroke_ = nil
		if not s then return end
		local list = s.parts
		pushAction("Place " .. #list, function()
			forget(list)
			for _, p in ipairs(list) do p.Parent = nil end
		end, function()
			for _, p in ipairs(list) do p.Parent = container end
		end)
	end

	fx.dragBegin = function()
		local cf = computePlacementCF(state.aim)
		if not cf then return end
		local part = placePart(cf, true)
		if part then stroke_ = { parts = { part }, last = cf.Position } end
	end

	connect(RunService.RenderStepped, function()
		local s = stroke_
		if not s then return end
		if state.tool ~= "Build" or #s.parts >= 300 or partCount() >= CONFIG.MaxParts
			or not UserInputService:IsMouseButtonPressed(Enum.UserInputType.MouseButton1) then
			finishStroke()
			return
		end
		local cf = computePlacementCF(state.aim)
		if not cf then return end
		local travel = cf.Position - s.last
		if travel.Magnitude < 0.01 then return end
		local gap = halfExtentAlong(cf, placementSize(), travel.Unit) * 2
		if travel.Magnitude >= math.max(gap * 0.95, 0.5) then
			local part = placePart(cf, true)
			if part then
				table.insert(s.parts, part)
				s.last = cf.Position
			end
		end
	end)
	connect(UserInputService.InputEnded, function(input)
		if input.UserInputType == Enum.UserInputType.MouseButton1 then finishStroke() end
	end)

