local ghost
local rayParams = RaycastParams.new()
rayParams.FilterType = Enum.RaycastFilterType.Exclude

local function castRay(ray)
	local ignore = { ghost }
	if player.Character then table.insert(ignore, player.Character) end
	rayParams.FilterDescendantsInstances = ignore
	return Workspace:Raycast(ray.Origin, ray.Direction * CONFIG.MaxPlaceDistance, rayParams)
end

local function isOverUI(pos)
	for _, frame in ipairs(uiRegions) do
		if frame.Visible then
			local ap, as = frame.AbsolutePosition, frame.AbsoluteSize
			if pos.X >= ap.X and pos.X <= ap.X + as.X and pos.Y >= ap.Y and pos.Y <= ap.Y + as.Y then return true end
		end
	end
	return false
end

-- v2: how a new part is aligned and snapped depends on state.placeMode
--   Surface  aligns to the part you aim at and snaps so the NEW part's edges line up with
--            that part's faces (4x4 blocks on an 8x8 slab tile perfectly, rotated slabs work)
--   Grid     snaps the centre to the world grid (the old behaviour)
--   Free     no snapping at all
function fx.axisOf(v, i)
	return i == 1 and v.X or (i == 2 and v.Y or v.Z)
end

local function computePlacementCF(result)
	if not result then return nil end
	local size = placementSize()
	local normal = result.Normal
	local mode = state.placeMode
	local inst = result.Instance
	local refPart = (mode == "Surface" and state.alignRot and inst and inst:IsA("BasePart") and not inst:IsA("Terrain")) and inst or nil
	local ref = refPart and refPart.CFrame.Rotation or CFrame.new()
	local rot = ref * state.rotation
	local pos = result.Position + normal * (halfExtentAlong(rot, size, normal) + state.placeLift)
	if mode == "Free" or not state.snapEnabled then
		return CFrame.new(pos) * rot
	end
	local step = gridStep()
	if refPart then
		local lp = ref:VectorToObjectSpace(pos - refPart.Position)
		local ln = ref:VectorToObjectSpace(normal)
		if math.max(math.abs(ln.X), math.abs(ln.Y), math.abs(ln.Z)) < 0.9 then
			return CFrame.new(pos) * rot -- slanted surface: snapping would push the part off it
		end
		local axes = { ref.XVector, ref.YVector, ref.ZVector }
		local out = {}
		for i = 1, 3 do
			local c = fx.axisOf(lp, i)
			if math.abs(fx.axisOf(ln, i)) > 0.9 then
				out[i] = c -- the contact axis stays exact
			else
				-- line the new part's edge up with this part's near OR far edge, whichever is closer
				local off = fx.axisOf(refPart.Size, i) / 2 - halfExtentAlong(rot, size, axes[i])
				local a = snap(c - off, step) + off
				local b = snap(c + off, step) - off
				out[i] = math.abs(a - c) <= math.abs(b - c) and a or b
			end
		end
		pos = refPart.Position + ref:VectorToWorldSpace(Vector3.new(out[1], out[2], out[3]))
	else
		local function axis(v, n)
			if math.abs(n) > 0.9 then
				return v -- keep the surface-contact axis exact
			end
			return snap(v, step)
		end
		pos = Vector3.new(axis(pos.X, normal.X), axis(pos.Y, normal.Y), axis(pos.Z, normal.Z))
	end
	return CFrame.new(pos) * rot
end

-- Aiming at empty space (sky, void) used to do nothing. Now a downward ray lands on a
-- virtual floor at state.groundY so you can always keep building.
function fx.aimFromRay(ray, result)
	if result then return result end
	local d = ray.Direction.Unit
	if d.Y >= -0.01 then return nil end
	local t = (state.groundY - ray.Origin.Y) / d.Y
	if t <= 0 or t > CONFIG.MaxPlaceDistance then return nil end
	return { Position = ray.Origin + d * t, Normal = Vector3.yAxis, Instance = nil }
end

local PLACE_MODES = { "Surface", "Grid", "Free" }
function fx.cycleMode()
	state.placeMode = PLACE_MODES[(table.find(PLACE_MODES, state.placeMode) or 0) % #PLACE_MODES + 1]
	ui.notify("Placement: " .. state.placeMode)
	refreshAll()
end

function fx.lift(direction)
	state.placeLift = math.clamp(state.placeLift + direction * gridStep(), -16, 64)
	ui.notify("Lift " .. fmt(state.placeLift) .. " studs")
	refreshAll()
end

