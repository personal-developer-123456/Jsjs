-- MENU GUARD: keeps scrolling the menu from pressing things by accident.
--  * track(sf)      watch a ScrollingFrame so we know when it is (or just was) moving
--  * busy(inst)     true while the menu page holding `inst` is scrolling / just stopped
--  * activated(b,f) like b.Activated:Connect(f) but ignores taps that were really
--                   scroll swipes, a drifting finger, or a touch that only stopped momentum
--  * cancelAll()    drops any slider drag in progress (panel closed, tab switched ...)
-- Kept on the `fx` table because the script sits near Lua's 200-local limit.
fx.menu = { lastScroll = {}, cancels = {} }

function fx.menu.track(sf)
	fx.menu.lastScroll[sf] = 0
	connect(sf:GetPropertyChangedSignal("CanvasPosition"), function()
		fx.menu.lastScroll[sf] = os.clock()
	end)
end

function fx.menu.busy(inst)
	local sf = inst:FindFirstAncestorWhichIsA("ScrollingFrame")
	local last = sf and fx.menu.lastScroll[sf]
	return last ~= nil and os.clock() - last < CONFIG.ScrollSettle
end

function fx.menu.activated(btn, callback)
	local startPos, ignore = nil, false
	btn.InputBegan:Connect(function(input)
		if input.UserInputType == Enum.UserInputType.Touch then
			startPos = input.Position
			ignore = fx.menu.busy(btn) -- landed on a moving page: this touch only stops it
		else
			startPos, ignore = nil, false
		end
	end)
	return btn.Activated:Connect(function(input, ...)
		if input and input.UserInputType == Enum.UserInputType.Touch then
			if ignore or fx.menu.busy(btn) then
				ignore = false
				return -- this touch only stopped a scrolling page (or the page is still moving)
			end
			if startPos and (input.Position - startPos).Magnitude > CONFIG.TapMoveLimit then
				return -- the finger travelled too far: that was a swipe, not a tap
			end
		end
		callback(input, ...)
	end)
end

function fx.menu.cancelAll()
	for _, cancel in ipairs(fx.menu.cancels) do cancel() end
end

