local marquee -- { StartPos = Vector2, Additive = bool } while a box-drag is in progress

local function updateMarqueeFrame(a, b)
	local topLeft = Vector2.new(math.min(a.X, b.X), math.min(a.Y, b.Y))
	local size = Vector2.new(math.abs(a.X - b.X), math.abs(a.Y - b.Y))
	marqueeFrame.Position = UDim2.fromOffset(topLeft.X, topLeft.Y)
	marqueeFrame.Size = UDim2.fromOffset(size.X, size.Y)
end

local function finishMarquee(endPos)
	local m = marquee
	marquee = nil
	marqueeFrame.Visible = false
	if not m or (endPos - m.StartPos).Magnitude < 4 then return end -- ignore accidental tiny drags
	local topLeft = Vector2.new(math.min(m.StartPos.X, endPos.X), math.min(m.StartPos.Y, endPos.Y))
	local bottomRight = Vector2.new(math.max(m.StartPos.X, endPos.X), math.max(m.StartPos.Y, endPos.Y))
	local cam = Workspace.CurrentCamera
	if not cam then return end
	if not m.Additive then clearSelection() end
	local hits = 0
	for _, p in ipairs(eligibleParts()) do
		local screen, onScreen = cam:WorldToViewportPoint(p.Position)
		if onScreen and screen.X >= topLeft.X and screen.X <= bottomRight.X and screen.Y >= topLeft.Y and screen.Y <= bottomRight.Y then
			addToSelection(p)
			hits = hits + 1
		end
	end
	selectionChanged()
	if hits > 0 then ui.notify("Box-selected " .. hits) end
end

