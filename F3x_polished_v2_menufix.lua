local function installV2()
	local Lighting = game:GetService("Lighting")
	local Debris = game:GetService("Debris")
	local SoundService = game:GetService("SoundService")
	local rgb = Color3.fromRGB

	local function tween(inst, props, seconds, style)
		local ok = pcall(function()
			TweenService:Create(inst, TweenInfo.new(seconds, style or Enum.EasingStyle.Quad, Enum.EasingDirection.Out), props):Play()
		end)
		if not ok then
			for key, value in pairs(props) do pcall(function() inst[key] = value end) end
		end
	end

	local function mouseLike()
		return UserInputService.MouseEnabled and UserInputService:GetLastInputType() ~= Enum.UserInputType.Touch
	end

	--// LIGHTING ---------------------------------------------------------------
	local LIGHT_KEYS = {
		"ClockTime", "Brightness", "Ambient", "OutdoorAmbient", "ColorShift_Top", "ColorShift_Bottom",
		"ExposureCompensation", "GlobalShadows", "FogColor", "FogStart", "FogEnd",
	}
	local FX_KEYS = { "bloom", "rays", "haze", "sat", "dof" }
	local EFFECT_CLASS = {
		bloom = "BloomEffect", rays = "SunRaysEffect", color = "ColorCorrectionEffect",
		dof = "DepthOfFieldEffect", haze = "Atmosphere",
	}
	local saved -- lighting as it was before this script touched it
	local made = {} -- effect instances this script created
	local stashed = {} -- the game's own Atmosphere, set aside while ours is active
	local lv = { bloom = 0, rays = 0, haze = 0, sat = 0, dof = 0, cycle = false }

	for _, child in ipairs(Lighting:GetChildren()) do -- leftovers from a previous run
		if child.Name:sub(1, 12) == "BuildStudio_" then child:Destroy() end
	end

	local function capture()
		if saved then return end
		saved = {}
		for _, key in ipairs(LIGHT_KEYS) do
			local ok, value = pcall(function() return Lighting[key] end)
			if ok then saved[key] = value end
		end
	end

	local function effect(key)
		capture()
		local e = made[key]
		if e and e.Parent then return e end
		e = Instance.new(EFFECT_CLASS[key])
		e.Name = "BuildStudio_" .. key
		if key == "haze" then
			for _, other in ipairs(Lighting:GetChildren()) do
				if other:IsA("Atmosphere") then
					table.insert(stashed, other)
					other.Parent = nil
				end
			end
			e.Color = rgb(199, 214, 235)
			e.Decay = rgb(106, 112, 125)
		elseif key == "bloom" then
			e.Size = 28
			e.Threshold = 0.9
		elseif key == "dof" then
			e.FocusDistance = 45
			e.InFocusRadius = 30
			e.NearIntensity = 0
		end
		e.Parent = Lighting
		made[key] = e
		return e
	end

	local function setFx(key, v)
		lv[key] = v
		local class = key == "sat" and "color" or key
		if v == 0 and not made[class] then return end -- nothing to switch off yet
		local e = effect(class)
		if key == "sat" then
			e.Saturation = v
		elseif key == "bloom" then
			e.Enabled = v > 0
			e.Intensity = v
		elseif key == "rays" then
			e.Enabled = v > 0
			e.Intensity = v
			e.Spread = 0.7
		elseif key == "haze" then -- Atmosphere has no Enabled switch: density 0 is "off"
			e.Density = v * 0.7
			e.Haze = v * 4
		elseif key == "dof" then
			e.Enabled = v > 0
			e.FarIntensity = v
		end
	end

	local PRESETS = {
		{ "Day", { ClockTime = 14, Brightness = 3, Ambient = rgb(90, 95, 105), OutdoorAmbient = rgb(130, 140, 155),
			ExposureCompensation = 0, GlobalShadows = true, FogEnd = 100000, FogColor = rgb(192, 200, 215) },
			{ bloom = 0.25, rays = 0.1, haze = 0.2, sat = 0.1, contrast = 0.05, tint = rgb(255, 252, 245) } },
		{ "Sunset", { ClockTime = 18.4, Brightness = 2.4, Ambient = rgb(110, 80, 90), OutdoorAmbient = rgb(150, 100, 90),
			ExposureCompensation = 0.1, FogEnd = 100000, FogColor = rgb(255, 160, 110) },
