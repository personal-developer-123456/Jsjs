-- Selection marks. `boxes[part]` is now a small list of adornments, built from the
-- Look tab settings (state.hlStyle / hlColor / hlThickness / hlFill).
function fx.buildMarks(part)
	local marks = {}
	local style = state.hlStyle
	if style == "Off" then return marks end
	local useBox = style == "Box" or style == "Both"
	if style == "Glow" or style == "Both" then
		if fx.glowCount < CONFIG.MaxHighlights then
			fx.glowCount += 1
			table.insert(marks, create("Highlight", {
				Adornee = part, FillColor = state.hlColor, FillTransparency = state.hlFill,
				OutlineColor = state.hlColor, OutlineTransparency = 0,
				DepthMode = Enum.HighlightDepthMode.AlwaysOnTop, Parent = fx.markFolder,
			}))
		else
			useBox = true -- big selections fall back to boxes once the Highlight budget is used
		end
	end
	if useBox then
		table.insert(marks, create("SelectionBox", {
			Adornee = part, Color3 = state.hlColor, LineThickness = state.hlThickness,
			SurfaceColor3 = state.hlColor, SurfaceTransparency = state.hlFill, Parent = adornFolder,
		}))
	end
	return marks
end

function fx.clearMarks(part)
	local marks = boxes[part]
	if not marks then return end
	boxes[part] = nil
	for _, m in ipairs(marks) do
		if m:IsA("Highlight") then fx.glowCount -= 1 end
		m:Destroy()
	end
end

-- style changed: throw the marks away and build them again
function fx.rebuildMarks()
	for _, part in ipairs(selection) do
		fx.clearMarks(part)
		boxes[part] = fx.buildMarks(part)
	end
end

-- colour / thickness / fill changed: update in place (cheap, used by the sliders)
function fx.restyleMarks()
	for _, marks in pairs(boxes) do
		for _, m in ipairs(marks) do
			if m:IsA("Highlight") then
				m.FillColor, m.OutlineColor, m.FillTransparency = state.hlColor, state.hlColor, state.hlFill
			else
				m.Color3, m.SurfaceColor3 = state.hlColor, state.hlColor
				m.LineThickness, m.SurfaceTransparency = state.hlThickness, state.hlFill
			end
		end
	end
end

