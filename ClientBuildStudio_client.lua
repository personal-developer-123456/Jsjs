local function slider(parent, title, minV, maxV, step, getValue, setValue, onCommit)
	local holder = create("Frame", { BackgroundTransparency = 1, Size = UDim2.new(1, 0, 0, 48), Parent = parent })
	label(holder, title, { Size = UDim2.new(0.6, 0, 0, 18), Color = THEME.SubText, TextSize = 12 })
	local valueLabel = label(holder, "", {
		Size = UDim2.new(0.4, 0, 0, 18), Position = UDim2.fromScale(0.6, 0), Align = Enum.TextXAlignment.Right, TextSize = 12,
	})
	local track = create("Frame", {
		Position = UDim2.new(0, 0, 0, 30), Size = UDim2.new(1, 0, 0, 8), BackgroundColor3 = THEME.Item, Parent = holder,
	})
	corner(track, 4)
	local fill = create("Frame", { Size = UDim2.fromScale(0, 1), BackgroundColor3 = THEME.Accent, Parent = track })
	corner(fill, 4)
	local knob = create("Frame", {
		AnchorPoint = Vector2.new(0.5, 0.5), Position = UDim2.fromScale(0, 0.5), Size = UDim2.fromOffset(22, 22),
		BackgroundColor3 = Color3.new(1, 1, 1), Parent = track,
	})
	corner(knob, 11)
	local hit = create("TextButton", {
		Text = "", BackgroundTransparency = 1, Position = UDim2.new(0, -8, 0, 16), Size = UDim2.new(1, 16, 0, 32), Parent = holder,
	})
	local scroller = parent:IsA("ScrollingFrame") and parent or parent:FindFirstAncestorWhichIsA("ScrollingFrame")
	local activeInput

	local function render()
		local v = getValue()
		local a = math.clamp((v - minV) / (maxV - minV), 0, 1)
		fill.Size = UDim2.fromScale(a, 1)
		knob.Position = UDim2.fromScale(a, 0.5)
		valueLabel.Text = fmt(v)
	end

	local function updateFrom(input)
		local a = math.clamp((input.Position.X - track.AbsolutePosition.X) / math.max(track.AbsoluteSize.X, 1), 0, 1)
		setValue(math.clamp(snap(minV + (maxV - minV) * a, step), minV, maxV))
		refreshAll()
	end

	hit.InputBegan:Connect(function(input)
		local t = input.UserInputType
		if t == Enum.UserInputType.MouseButton1 or t == Enum.UserInputType.Touch then
			activeInput = input
			if scroller then
				scroller.ScrollingEnabled = false -- stop the page scrolling while dragging
			end
			updateFrom(input)
		end
	end)
	connect(UserInputService.InputChanged, function(input)
		if activeInput and (input == activeInput or input.UserInputType == Enum.UserInputType.MouseMovement) then updateFrom(input) end
	end)
	connect(UserInputService.InputEnded, function(input)
		if activeInput and (input == activeInput or input.UserInputType == Enum.UserInputType.MouseButton1) then
			activeInput = nil
			if scroller then scroller.ScrollingEnabled = true end
			if onCommit then onCommit() end
		end
	end)
	refresher(render)
	return holder
end

local function stepper(parent, title, step, minV, maxV, getValue, setValue)
	local holder = create("Frame", { BackgroundColor3 = THEME.Item, Size = UDim2.new(1, 0, 0, 40), Parent = parent })
	corner(holder)
	label(holder, title, { Position = UDim2.fromOffset(10, 0), Size = UDim2.fromOffset(30, 40), Font = THEME.FontBold })
	local function apply(v)
		setValue(math.clamp(v, minV, maxV))
		refreshAll()
	end
	local minus = button(holder, "-", UDim2.fromOffset(34, 30), function()
		apply(getValue() - step)
	end, THEME.ItemLight)
	minus.AnchorPoint = Vector2.new(0, 0.5)
	minus.Position = UDim2.new(0, 40, 0.5, 0)
	local box = create("TextBox", {
		Text = "", Font = THEME.Font, TextSize = 14, TextColor3 = THEME.Text, BackgroundColor3 = THEME.Panel,
		ClearTextOnFocus = false, AnchorPoint = Vector2.new(0, 0.5), Position = UDim2.new(0, 78, 0.5, 0),
		Size = UDim2.new(1, -124, 0, 30), Parent = holder,
	})
	corner(box, 6)
	box.FocusLost:Connect(function()
		local n = tonumber(box.Text)
		if n then
			apply(n)
		else
			refreshAll()
		end
	end)
	local plus = button(holder, "+", UDim2.fromOffset(34, 30), function()
		apply(getValue() + step)
	end, THEME.ItemLight)
	plus.AnchorPoint = Vector2.new(1, 0.5)
	plus.Position = UDim2.new(1, -6, 0.5, 0)
	refresher(function()
		box.Text = fmt(getValue())
	end)
	return holder
end

