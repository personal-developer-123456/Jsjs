refreshHandles = function()
	local p = primaryPart()
	for mode, h in pairs(handles) do
		local active = p ~= nil and state.tool == "Select" and state.handleMode == mode
		h.Adornee = active and p or nil
	end
end

local drag = nil -- active handle drag data

local function beginDrag()
	local p = primaryPart()
	if not p then return end
	local startCFs = {}
	for _, part in ipairs(selection) do startCFs[part] = part.CFrame end
	drag = {
		Before = snapshotMany(selection),
		StartCFs = startCFs,
		Primary = p,
		PrimaryCF = p.CFrame,
		PrimarySize = p.Size,
	}
end

local function endDrag(name)
	if drag then
		commitChange(name, drag.Before)
		drag = nil
	end
end

local function dragSnap(value)
	return state.snapEnabled and snap(value, gridStep()) or value
end

-- Move: slide every selected part along the dragged face normal
handles.Move.MouseButton1Down:Connect(beginDrag)
handles.Move.MouseDrag:Connect(function(face, distance)
	if not drag then return end
	local dir = drag.PrimaryCF:VectorToWorldSpace(Vector3.FromNormalId(face))
	local offset = dir * dragSnap(distance)
	for part, cf in pairs(drag.StartCFs) do part.CFrame = cf + offset end
end)
handles.Move.MouseButton1Up:Connect(function()
	endDrag("Move")
end)

-- Scale: stretch the primary part along one axis, keeping the far face fixed
handles.Scale.MouseButton1Down:Connect(beginDrag)
handles.Scale.MouseDrag:Connect(function(face, distance)
	if not drag then return end
	local axisVec = Vector3.FromNormalId(face)
	local axisAbs = Vector3.new(math.abs(axisVec.X), math.abs(axisVec.Y), math.abs(axisVec.Z))
	local start = drag.PrimarySize
	local grown = start + axisAbs * dragSnap(distance)
	grown = Vector3.new(
		math.clamp(grown.X, CONFIG.MinSize, CONFIG.MaxSize),
		math.clamp(grown.Y, CONFIG.MinSize, CONFIG.MaxSize),
		math.clamp(grown.Z, CONFIG.MinSize, CONFIG.MaxSize)
	)
	local delta = (grown - start):Dot(axisAbs)
	drag.Primary.Size = grown
	drag.Primary.CFrame = drag.PrimaryCF * CFrame.new(axisVec * (delta / 2))
end)
handles.Scale.MouseButton1Up:Connect(function()
	endDrag("Scale")
end)

-- Rotate: spin every selected part around the primary part's centre
handles.Rotate.MouseButton1Down:Connect(beginDrag)
handles.Rotate.MouseDrag:Connect(function(axis, relativeAngle)
	if not drag then return end
	local deg = math.deg(relativeAngle)
	if state.snapEnabled then deg = snap(deg, angleStep()) end
	local axisVec = drag.PrimaryCF:VectorToWorldSpace(Vector3.FromAxis(axis))
	local R = CFrame.fromAxisAngle(axisVec, math.rad(deg))
	local pivot = drag.PrimaryCF.Position
	for part, cf in pairs(drag.StartCFs) do part.CFrame = CFrame.new(pivot) * R * CFrame.new(-pivot) * cf end
end)
handles.Rotate.MouseButton1Up:Connect(function()
	endDrag("Rotate")
end)

