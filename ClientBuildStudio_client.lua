-- Distance from a part's centre to its surface along world direction `dir`
local function halfExtentAlong(cf, size, dir)
	return math.abs(cf.RightVector:Dot(dir)) * size.X / 2
		+ math.abs(cf.UpVector:Dot(dir)) * size.Y / 2
		+ math.abs(cf.LookVector:Dot(dir)) * size.Z / 2
end

local function materialFromName(name)
	local ok, mat = pcall(function()
		return Enum.Material[name]
	end)
	return ok and mat or Enum.Material.SmoothPlastic
end

