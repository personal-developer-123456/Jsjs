local function placementSize()
	local s = state.size
	if state.shape.Name == "Ball" then return Vector3.new(s.X, s.X, s.X) end
	return s
end

local function createPart(shapeName, size, cf, style)
	local def = SHAPE_BY_NAME[shapeName] or SHAPES[1]
	local part = Instance.new(def.Class)
	if def.Shape then part.Shape = def.Shape end
	part.Name = def.Name
	part.Size = size
	part.CFrame = cf
	part.TopSurface = Enum.SurfaceType.Smooth
	part.BottomSurface = Enum.SurfaceType.Smooth
	for key, value in pairs(style or currentStyle()) do part[key] = value end
	part:SetAttribute("BuildShape", def.Name)
	part.Parent = container
	return part
end

local function placePart(cf)
	if partCount() >= CONFIG.MaxParts then
		ui.notify("Part limit reached (" .. CONFIG.MaxParts .. ")")
		return nil
	end
	local part = createPart(state.shape.Name, placementSize(), cf)
	pushAction("Place " .. part.Name, function()
		forget({ part })
		part.Parent = nil
	end, function()
		part.Parent = container
	end)
	return part
end

local function deleteParts(parts)
	if #parts == 0 then return end
	local list = table.clone(parts)
	forget(list)
	for _, p in ipairs(list) do p.Parent = nil end
	pushAction("Delete " .. #list, function()
		for _, p in ipairs(list) do p.Parent = container end
	end, function()
		forget(list)
		for _, p in ipairs(list) do p.Parent = nil end
	end)
end

local function duplicateSelection()
	if #selection == 0 then
		ui.notify("Select something first")
		return
	end
	if partCount() + #selection > CONFIG.MaxParts then
		ui.notify("Part limit reached")
		return
	end
	local off = math.max(2, gridStep())
	local clones = {}
	for _, part in ipairs(selection) do
		local clone = part:Clone()
		clone.CFrame = part.CFrame + Vector3.new(off, 0, off)
		clone.Parent = container
		table.insert(clones, clone)
	end
	clearSelection()
	for _, c in ipairs(clones) do addToSelection(c) end
	selectionChanged()
	pushAction("Duplicate " .. #clones, function()
		forget(clones)
		for _, c in ipairs(clones) do c.Parent = nil end
	end, function()
		for _, c in ipairs(clones) do c.Parent = container end
	end)
end

local function applyStyleToParts(parts, style)
	changeParts("Style", parts, function()
		for _, p in ipairs(parts) do
			for key, value in pairs(style) do p[key] = value end
		end
	end)
end

