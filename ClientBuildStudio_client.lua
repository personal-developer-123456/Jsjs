--// HISTORY (UNDO / REDO) ----------------------------------------------------
local history = { undoStack = {}, redoStack = {} }

local function pushAction(name, undoFn, redoFn)
	table.insert(history.undoStack, { Name = name, Undo = undoFn, Redo = redoFn })
	if #history.undoStack > CONFIG.HistoryLimit then table.remove(history.undoStack, 1) end
	table.clear(history.redoStack)
	ui.refreshContext()
end

local function undo()
	local action = table.remove(history.undoStack)
	if not action then
		ui.notify("Nothing to undo")
		return
	end
	action.Undo()
	table.insert(history.redoStack, action)
	ui.notify("Undo: " .. action.Name)
	ui.refreshContext()
end

local function redo()
	local action = table.remove(history.redoStack)
	if not action then
		ui.notify("Nothing to redo")
		return
	end
	action.Redo()
	table.insert(history.undoStack, action)
	ui.notify("Redo: " .. action.Name)
	ui.refreshContext()
end

-- Property snapshots power every transform / style undo
local TRACKED = { "Size", "CFrame", "Color", "Material", "Transparency", "Reflectance", "Anchored", "CanCollide" }

local function snapshot(part)
	local s = {}
	for _, key in ipairs(TRACKED) do s[key] = part[key] end
	return s
end

local function restore(part, s)
	for _, key in ipairs(TRACKED) do -- ordered: Size before CFrame
		part[key] = s[key]
	end
end

local function snapshotMany(parts)
	local t = {}
	for _, p in ipairs(parts) do t[p] = snapshot(p) end
	return t
end

local function sameSnapshot(a, b)
	for _, key in ipairs(TRACKED) do
		if a[key] ~= b[key] then return false end
	end
	return true
end

-- Compare "before" to the current state and push one undo entry if changed
local function commitChange(name, before)
	local after, changed = {}, false
	for part, snap0 in pairs(before) do
		after[part] = snapshot(part)
		if not sameSnapshot(snap0, after[part]) then changed = true end
	end
	if not changed then return end
	pushAction(name, function()
		for part, s in pairs(before) do restore(part, s) end
	end, function()
		for part, s in pairs(after) do restore(part, s) end
	end)
end

local function changeParts(name, parts, mutate)
	if #parts == 0 then return end
	local before = snapshotMany(parts)
	mutate()
	commitChange(name, before)
end

