local explorerRows = {} -- part -> row Frame

local function makeExplorerRow(part)
	local rowF = create("Frame", { BackgroundColor3 = THEME.Item, Size = UDim2.new(1, 0, 0, 30), Parent = explorerList })
	corner(rowF, 6)
	local rowList = listLayout(rowF, 4, true)
	rowList.VerticalAlignment = Enum.VerticalAlignment.Center
	create("UIPadding", { PaddingLeft = UDim.new(0, 6), PaddingRight = UDim.new(0, 6), Parent = rowF })

	local nameBtn = create("TextButton", {
		Text = part.Name, Font = THEME.Font, TextSize = 12, TextColor3 = THEME.Text,
		TextXAlignment = Enum.TextXAlignment.Left, TextTruncate = Enum.TextTruncate.AtEnd,
		BackgroundTransparency = 1, Size = UDim2.new(1, -140, 1, 0), Parent = rowF,
	})
	nameBtn.Activated:Connect(function()
		if lockedParts[part] then
			ui.notify("Locked - unlock to select")
			return
		end
		selectOnly(part)
	end)

	local nameBox = create("TextBox", {
		Text = part.Name, Font = THEME.Font, TextSize = 12, TextColor3 = THEME.Text,
		BackgroundColor3 = THEME.Panel, Visible = false, ClearTextOnFocus = false,
		Size = UDim2.new(1, -140, 0, 22), Parent = rowF,
	})
	corner(nameBox, 4)
	nameBox.FocusLost:Connect(function(enterPressed)
		if enterPressed and nameBox.Text ~= "" then
			part.Name = nameBox.Text
			nameBtn.Text = part.Name
		else
			nameBox.Text = part.Name
		end
		nameBox.Visible = false
		nameBtn.Visible = true
	end)

	button(rowF, "Ren", UDim2.fromOffset(28, 22), function()
		nameBox.Text = part.Name
		nameBtn.Visible = false
		nameBox.Visible = true
		nameBox:CaptureFocus()
	end, THEME.ItemLight).TextSize = 10

	local lockBtn = button(rowF, lockedParts[part] and "Lckd" or "Lock", UDim2.fromOffset(32, 22), nil,
		lockedParts[part] and THEME.Accent or THEME.ItemLight)
	lockBtn.TextSize = 10
	lockBtn.Activated:Connect(function()
		setLocked(part, not lockedParts[part])
		lockBtn.Text = lockedParts[part] and "Lckd" or "Lock"
		lockBtn.BackgroundColor3 = lockedParts[part] and THEME.Accent or THEME.ItemLight
	end)

	local hideBtn = button(rowF, hiddenParts[part] and "Hidn" or "Hide", UDim2.fromOffset(32, 22), nil,
		hiddenParts[part] and THEME.Accent or THEME.ItemLight)
	hideBtn.TextSize = 10
	hideBtn.Activated:Connect(function()
		setHidden(part, not hiddenParts[part])
		hideBtn.Text = hiddenParts[part] and "Hidn" or "Hide"
		hideBtn.BackgroundColor3 = hiddenParts[part] and THEME.Accent or THEME.ItemLight
	end)

	button(rowF, "Del", UDim2.fromOffset(28, 22), function()
		if lockedParts[part] then
			ui.notify("Locked - unlock to delete")
			return
		end
		deleteParts({ part })
	end, THEME.Bad).TextSize = 10

	return rowF
end

local function clearExplorerRows()
	for _, rowF in pairs(explorerRows) do rowF:Destroy() end
	table.clear(explorerRows)
end

rebuildExplorerList = function()
	clearExplorerRows()
	local parts = container:GetChildren()
	if #parts > 300 then ui.notify("Large build (" .. #parts .. ") - list may be slow") end
	for _, p in ipairs(parts) do
		if p:IsA("BasePart") then explorerRows[p] = makeExplorerRow(p) end
	end
end

